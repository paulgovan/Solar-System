import { registerOrbitProvider } from './providers.js';
import { centuriesTT } from './time.js';

const toTT = (jd) => J2000 + centuriesTT(jd) * 36525;

// 'satellite': parent-relative mean-element orbit. The orbit line is the current
// precessing ellipse; it is resampled often enough that node/apsis motion is invisible.
registerOrbitProvider('satellite', {
  relative: true,
  position: (body, jd) => satellitePosition(body.id, toTT(jd)),
  path: (body, jd, segments) => {
    const el = SATELLITE_ELEMENTS[body.id];
    const drift = Math.max(Math.abs(el.dnode), Math.abs(el.dperi) * Math.min(1, el.e * 50), 1e-6); // deg/day of visible change
    return { ...satelliteOrbitPath(body.id, toTT(jd), segments), startJD: jd, refreshDays: Math.min(30, Math.max(0.05, 0.5 / drift)) };
  },
  phase: (body, jd, path) => {
    const dE = satelliteEccentricAnomaly(body.id, toTT(jd)) - path.E0;
    return ((dE / TWO_PI) % 1 + 1) % 1;
  },
});

// Pluto and Charon orbit their common barycentre, about 2,100 km from Pluto's centre.
// The planet elements give the barycentre; this offset moves Pluto off it.
export const CHARON_PLUTO_MASS_RATIO = 106.1 / 869.6; // GM Charon / GM Pluto (PLU060)

/** Pluto's offset (AU, ecliptic J2000) from the Pluto–Charon barycentre for a TT Julian Date. */
export function plutoBarycentricOffset(jdTT) {
  const c = satellitePosition('charon', jdTT);
  const k = -CHARON_PLUTO_MASS_RATIO / (1 + CHARON_PLUTO_MASS_RATIO);
  return { x: c.x * k, y: c.y * k, z: c.z * k };
}
