/** Register (or replace) one satellite's elements. */
export function defineSatellite(id, el) {
  SATELLITE_ELEMENTS[id] = el;
}

const norm = (x) => ((x % TWO_PI) + TWO_PI) % TWO_PI;

/** Unit vectors (equatorial ICRF) of the reference frame: x = ascending node on the ICRF equator, z = pole. */
function refFrame(el) {
  const a = el.pole[0] * DEG, d = el.pole[1] * DEG;
  const z = [Math.cos(d) * Math.cos(a), Math.cos(d) * Math.sin(a), Math.sin(d)];
  const x = [-Math.sin(a), Math.cos(a), 0];
  const y = [z[1] * x[2] - z[2] * x[1], z[2] * x[0] - z[0] * x[2], z[0] * x[1] - z[1] * x[0]];
  return { x, y, z };
}

/**
 * Precessed elements at `d` days (TT) from J2000. Angles in radians.
 */
export function satelliteElements(el, d) {
  const node = (el.node + el.dnode * d) * DEG;
  const peri = (el.peri + el.dperi * d) * DEG;
  let lambda = el.lambda + el.n * d + (el.n2 || 0) * d * d;
  for (const [A, f, ph] of el.lib || []) lambda += A * Math.sin((f * d + ph) * DEG); // long-period terms
  lambda *= DEG;
  return { a: el.a, e: el.e, i: el.i * DEG, node, peri, M: norm(lambda - peri) };
}

/** Position in the reference plane frame (km), given elements and eccentric anomaly. */
function inPlane(k, E) {
  const { a, e, i, node, peri } = k;
  const w = peri - node;
  const xp = a * (Math.cos(E) - e);
  const yp = a * Math.sqrt(1 - e * e) * Math.sin(E);
  const cw = Math.cos(w), sw = Math.sin(w), cO = Math.cos(node), sO = Math.sin(node), ci = Math.cos(i), si = Math.sin(i);
  const x1 = xp * cw - yp * sw, y1 = xp * sw + yp * cw;
  return [x1 * cO - y1 * ci * sO, x1 * sO + y1 * ci * cO, y1 * si];
}

function toEcliptic(f, p) {
  const ex = f.x[0] * p[0] + f.y[0] * p[1] + f.z[0] * p[2];
  const ey = f.x[1] * p[0] + f.y[1] * p[1] + f.z[1] * p[2];
  const ez = f.x[2] * p[0] + f.y[2] * p[1] + f.z[2] * p[2];
  const v = equatorialToEcliptic(ex, ey, ez);
  return { x: v.x / AU_KM, y: v.y / AU_KM, z: v.z / AU_KM };
}

/**
 * Parent-relative position (AU, ecliptic J2000) of a satellite.
 * `jdTT` is a Terrestrial Time Julian Date.
 */
export function satellitePosition(id, jdTT) {
  const el = SATELLITE_ELEMENTS[id];
  const k = satelliteElements(el, jdTT - J2000);
  return toEcliptic(refFrame(el), inPlane(k, solveKepler(k.M, k.e)));
}

/** Eccentric anomaly (rad) at jdTT. */
export function satelliteEccentricAnomaly(id, jdTT) {
  const k = satelliteElements(SATELLITE_ELEMENTS[id], jdTT - J2000);
  return solveKepler(k.M, k.e);
}

/**
 * One full orbit: the precessing ellipse frozen at jdTT, sampled uniformly in eccentric
 * anomaly starting at the satellite's current position. Returns { points, E0 }.
 */
export function satelliteOrbitPath(id, jdTT, segments) {
  const el = SATELLITE_ELEMENTS[id];
  const k = satelliteElements(el, jdTT - J2000);
  const f = refFrame(el);
  const E0 = solveKepler(k.M, k.e);
  const points = [];
  for (let s = 0; s <= segments; s++) points.push(toEcliptic(f, inPlane(k, E0 + (s / segments) * TWO_PI)));
  return { points, E0 };
}

/** Orbital period (days) from the mean-longitude rate. */
export function satellitePeriod(id) {
  return 360 / Math.abs(SATELLITE_ELEMENTS[id].n);
}

