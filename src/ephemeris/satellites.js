// Major moons other than the Galileans: precessing-ellipse mean elements.
//
// Model and frames follow JPL's "Planetary Satellite Mean Elements"
// (https://ssd.jpl.nasa.gov/sats/elem/): an ellipse with uniformly precessing
// node and periapsis, referred either to the satellite's local Laplace plane
// or to the planet's equator, with the node measured from the ascending node of
// that reference plane on the ICRF equator. Epoch 2000 Jan 1.5 TDB.
//
// The published table rounds angles to 0.1° and some periods to 4–5 digits,
// which drifts by degrees per decade for the fast moons (Phobos, Deimos,
// Triton…). The constants below were therefore refined by a least-squares fit
// of the same model to JPL Horizons vectors (1950–2050), starting from the
// table values, adding long-period libration terms where resonances need them.
// Accuracy (1950–2050, parent-relative direction): ≤ 0.33° for every moon, most
// below 0.1° — see tests/satellites.test.js. Outside that span errors grow
// slowly (decades → tenths of a degree; Mimas' libration and Phobos' tidal
// acceleration are the first to degrade).

import { DEG, J2000, AU_KM } from './constants.js';
import { equatorialToEcliptic } from './rotation.js';
import { solveKepler } from './kepler.js';

